"""Пороги аналітики — в одному місці й у файлі, а не в тілі коду.

Кожне число тут — рішення, яке колись доведеться переглянути, коли база
підросте. Тому вони лежать поруч, підписані, і зберігаються в
`data/analytics_settings.json`, звідки їх можна змінити без правки коду.
"""
from __future__ import annotations

import json
from dataclasses import asdict, dataclass, fields
from pathlib import Path

from ..config import DATA_DIR

PATH = Path(DATA_DIR) / "analytics_settings.json"


@dataclass(frozen=True)
class Settings:
    # --- Розмір вибірки -------------------------------------------------------
    # Нижче цього числа сегмент не показуємо взагалі: 27 із 37 комбінацій
    # (кімнатність × стан × ринок) мають ≥30 об'єктів і покривають 98% бази,
    # а решта — вибірки по кілька квартир, де медіана нічого не описує.
    min_sample: int = 30
    # Для порівняння двох джерел між собою потрібні обидві вибірки, тож поріг
    # тут окремий і трохи нижчий — інакше зіставних пар не лишиться взагалі.
    min_sample_source: int = 25

    # --- Відсікання викидів ---------------------------------------------------
    # Метод: межі Тьюкі в логарифмічному просторі. Ціни розподілені зі скосом
    # вправо, тому в лінійному просторі верхня межа завжди відсікає забагато,
    # а нижня — нічого. Логарифм робить розподіл симетричнішим.
    # k=3.0 — це «далекі викиди» за Тьюкі: прибирає одруківки в нулях, але не
    # чіпає справді дорогі квартири.
    outlier_k: float = 3.0
    # Менше за стільки значень межі рахувати немає сенсу — беремо вибірку як є.
    outlier_min_n: int = 20

    # --- Порівняння за площею -------------------------------------------------
    # Ціна за м² залежить від площі навіть усередині однієї кімнатності:
    # виміряно 14.8% розкиду між крайніми квартилями площі однокімнатних.
    # Тому об'єкт порівнюємо зі схожими за площею, а не з усім сегментом.
    area_band_pct: float = 0.15
    # Якщо у вузькій смузі замало об'єктів, смуга розширюється до цієї межі,
    # а якщо й тоді замало — порівняння йде без обмеження за площею, і про це
    # написано в підписі.
    area_band_max_pct: float = 0.35

    # --- Прогнозування --------------------------------------------------------
    # Точки ряду — тижневі медіани сегмента. Тиждень, а не місяць: сегменти
    # мають сотні об'єктів, тижнева медіана стабільна, а місячна дає замало
    # точок за прийнятний час.
    forecast_fit_points: int = 12      # мінімум точок, щоб узагалі щось підганяти
    forecast_backtest_points: int = 6  # скільки останніх точок ховаємо для бектесту
    # Стеля горизонту прогнозу як частка спостереженого періоду. Екстраполяція
    # на довше за третину історії — це вже не прогноз.
    forecast_horizon_ratio: float = 1 / 3
    # Прогноз із помилкою бектесту вище за цю межу користувачу не показуємо.
    forecast_max_mape: float = 10.0
    # Сезонність не заявляємо, доки немає двох повних річних циклів.
    seasonality_years: int = 2

    # --- Довіра до склейки ----------------------------------------------------
    # Розбіжність цін між майданчиками на «той самий» об'єкт, вище за яку
    # склейку варто перечитати очима. Невелика різниця нормальна — майданчики
    # оновлюються не одночасно. Різниця в півтора раза найчастіше означає, що
    # зведено дві різні квартири, і подавати таке як «історію ціни» не можна.
    merge_suspect_spread: float = 25.0

    # --- Строк продажу --------------------------------------------------------
    # Мінімум подій зняття з продажу, щоб крива виживання щось означала.
    # Нижче цього числа показуємо «недостатньо даних», а не пласку лінію.
    survival_min_events: int = 50

    def save(self) -> None:
        PATH.write_text(json.dumps(asdict(self), indent=2, ensure_ascii=False))


def load() -> Settings:
    """Читає налаштування з файла; невідомі ключі ігнорує, відсутні — за умовчанням."""
    if not PATH.exists():
        return Settings()
    try:
        raw = json.loads(PATH.read_text())
    except (json.JSONDecodeError, OSError):
        return Settings()
    known = {f.name for f in fields(Settings)}
    return Settings(**{k: v for k, v in raw.items() if k in known})
